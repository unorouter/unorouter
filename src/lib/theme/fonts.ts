type FontKind = "sans" | "mono" | "display";

export type FontOption = {
  id: string;
  label: string;
  cssVar: string;
  varName: string;
  kinds: FontKind[];
  accessibility?: boolean;
};

function font(
  id: string,
  label: string,
  loader: { variable: string },
  kinds: FontKind[],
  accessibility?: true,
): FontOption {
  return {
    id,
    label,
    cssVar: loader.variable,
    varName: `--font-${id}`,
    kinds,
    ...(accessibility ? { accessibility } : {}),
  };
}

